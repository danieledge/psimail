def colour_of(name, c, extra=None):
    m = dict(GREYS); m.update(CUBE_GREYS); m.update(COLOUR.get(name, {}))
    if extra: m.update(extra)
    if c == '.':
        return (255, 255, 255)
    for v in m[c]:
        if v % 51:
            raise SystemExit(f'{name}: {m[c]} is not one of the 256 colours\' cube')
    return m[c]


# (1.14) a toolbar picture of COLOUR_TOOL: the art, its 2-pixel shadow and
# its own mask (black = drawn); every colour from the cube
def tool_picture(out, name, w, h):
    rows, tw, th = parse(COLOUR_TOOL[name])
    if (tw, th) != (w, h):
        raise SystemExit(f'{name}: the colour picture is not {w}x{h}')
    img = Image.new('RGB', (w, h), (255, 255, 255))
    mask = Image.new('1', (w, h), 1)
    drawn = [[c != '.' for c in r] for r in rows]
    for y in range(h):
        for x in range(w):
            c = rows[y][x]
            if c != '.':
                if c not in TOOL_PAL:
                    raise SystemExit(f'{name}: bad pixel {c!r}')
                rgb = TOOL_PAL[c]
            elif y >= 2 and x >= 2 and drawn[y - 2][x - 2]:
                rgb = TOOL_SHADOW
            else:
                continue
            for v in rgb:
                if v % 51:
                    raise SystemExit(f'{name}: {rgb} is not one of the 256 colours\' cube')
            img.putpixel((x, y), rgb)
            mask.putpixel((x, y), 0)
    fi = os.path.join(out, f'{name}_c.bmp')
    fm = os.path.join(out, f'{name}_cm.bmp')
    img.save(fi)
    mask.convert('RGB').save(fm)
    return fi, fm


def parse(art):
    rows = [r for r in art.strip('\n').split('\n')]
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, '.') for r in rows]
    return rows, w, len(rows)


